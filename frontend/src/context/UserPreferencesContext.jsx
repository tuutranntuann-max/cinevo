export function UserPreferencesProvider({ children }) {
  const [preferences, setPreferences] = useState(() => {
    try {
      const saved = JSON.parse(localStorage.getItem(PREFERENCES_KEY) || "{}");
      return {
        theme: saved.theme === "light" ? "light" : "dark",
        language: saved.language === "en" ? "en" : "vi",
      };
    } catch {
      return { theme: "dark", language: "vi" };
    }
  });

  useEffect(() => {
    localStorage.setItem(PREFERENCES_KEY, JSON.stringify(preferences));
    document.documentElement.lang = preferences.language;
  }, [preferences]);

  const value = useMemo(() => ({
    ...preferences,
    setTheme: (theme) => setPreferences((current) => ({ ...current, theme })),
    setLanguage: (language) => setPreferences((current) => ({ ...current, language })),
    t: (text) => preferences.language === "en" ? (EN[text] || text) : text,
  }), [preferences]);

  return <UserPreferencesContext.Provider value={value}>{children}</UserPreferencesContext.Provider>;
}

export function useUserPreferences() {
  const context = useContext(UserPreferencesContext);
  if (!context) throw new Error("useUserPreferences must be used within UserPreferencesProvider");
  return context;
}
